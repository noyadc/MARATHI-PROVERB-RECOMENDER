def uniquify(values, suffixes):
    seen = {}
    result = []
    for value in values:
        count = seen.get(value, 0)
        if count == 0:
            result.append(value)
        else:
            suffix = suffixes[(count - 1) % len(suffixes)]
            if value and value[-1] in '.?!':
                result.append(f"{value[:-1]} {suffix}{value[-1]}")
            else:
                result.append(f"{value} {suffix}")
        seen[value] = count + 1
    return result


